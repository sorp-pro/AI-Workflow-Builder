#!/usr/bin/env node
// Вход участника: регистрация и согласие на запись обращений.
//
//   node scripts/vhod.mjs                          кто вошёл; никого не заводит
//   node scripts/vhod.mjs "Имя"                    войти под своим именем
//   node scripts/vhod.mjs "Имя" КОД-ПРИГЛАШЕНИЯ    то же, с кодом в руках
//   node scripts/vhod.mjs --ключ sorp_…            войти готовым ключом
//   node scripts/vhod.mjs --согласие               разрешить запись обращений
//   node scripts/vhod.mjs --отозвать               запретить запись
//   node scripts/vhod.mjs --выйти                  забыть ключ на этой машине
//
// ── Почему согласие отдельно от входа ────────────────────────────────────────
// Войти и разрешить отправлять свою переписку — разные решения. Человек может
// пользоваться разбором и не отдавать вопросы: плагин от этого работает так же.
// Слить их в одно значило бы получить согласие обманом — за него платят
// доверием, и один раз.

import { rmSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { userInfo } from 'node:os';
import { прочитать, записать, где, согласился, кодПриглашения } from '../hooks/nastroyki.mjs';
import { позвать } from '../hooks/stend.mjs';

const доводы = process.argv.slice(2);
const флаг = (и) => доводы.includes(и);
const значение = (и) => {
  const к = доводы.indexOf(и);
  return к === -1 ? null : доводы[к + 1];
};

/** Ключ уходит в заголовок, а тот держит только байты: кириллица валит fetch. */
const годныйКлюч = (к) => /^[\x21-\x7E]+$/.test(String(к || '').trim());

/**
 * Как зовут человека, если он не назвался.
 *
 * ── Почему из git, а не из логина ────────────────────────────────────────────
 * Имя в журнале читают люди: «Denis Zaitsev» говорит, кто спрашивал, «mysdc» —
 * нет. Git знает настоящее имя почти на всякой рабочей машине: оно стоит в
 * каждом коммите. Логин остаётся на случай, когда git не настроен, — и тогда
 * участнику лучше назваться самому, о чём ему и говорят.
 */
function самоимя() {
  try {
    const и = execFileSync('git', ['config', '--get', 'user.name'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (и.length >= 2) return { имя: и, откуда: 'git config user.name' };
  } catch {
    // git не поставлен или имя не задано — ниже есть логин.
  }
  const л = String(userInfo().username || '').trim();
  if (л.length >= 2) return { имя: л, откуда: 'логин в системе' };
  return { имя: null, откуда: null };
}

// Через общий способ связи: он умеет ходить через прокси изолированных сред,
// а голый fetch там висит до таймаута.
async function опознать(ключ) {
  const о = await позвать('/whoami', { ключ, ждать: 6000 });
  if (о.код === 401) return { опознан: false, почему: 'ключ не опознан или выключен' };
  if (!о.вышло) return { опознан: false, почему: о.почему ?? `стенд ответил ${о.код}` };
  return { опознан: true, имя: о.тело.имя, роль: о.тело.роль };
}

// ---------- выход ----------

if (флаг('--выйти')) {
  if (existsSync(где())) {
    rmSync(где());
    console.log(`Ключ забыт. Файл ${где()} удалён.`);
    console.log('В журнале стенда участник и его прошлые обращения остаются: журнал, из которого');
    console.log('можно вычистить свои следы, ничего не стоит.');
  } else {
    console.log('Ключа на этой машине и не было.');
  }
  process.exit(0);
}

// ---------- согласие ----------

if (флаг('--согласие')) {
  const н = прочитать();
  if (!н.ключ) {
    console.error('Сначала войдите: /vhod');
    process.exit(1);
  }
  записать({ согласие: true, согласиеДано: new Date().toISOString().slice(0, 16).replace('T', ' ') });
  console.log('Согласие записано. Теперь ваши вопросы уходят в журнал разбора под вашим именем.');
  console.log('Ответы Claude не записываются — только то, что спрашиваете вы.');
  console.log('Отозвать в любой момент: /vhod --отозвать');
  process.exit(0);
}

if (флаг('--отозвать')) {
  записать({ согласие: false });
  console.log('Согласие отозвано. Обращения больше не записываются.');
  console.log('Записанное раньше остаётся на стенде — удалить его отсюда нельзя.');
  process.exit(0);
}

// ── Почему дальше всё в функции ──────────────────────────────────────────────
// process.exit сразу после fetch валит Node ассерцией в libuv: сокет ещё
// закрывается. Человек видит вместо своей ошибки чужой краш. Возврат из функции
// даёт сокету закрыться самому.
async function главное() {
  // ---------- вход готовым ключом ----------

  const готовый = значение('--ключ');
  if (готовый) {
    if (!годныйКлюч(готовый)) {
      console.error('В ключе есть символы, которых в нём быть не может — похоже, скопирован с лишним куском.');
      return 1;
    }
    const кто = await опознать(готовый.trim());
    if (!кто.опознан) {
      console.error(`Войти не вышло: ${кто.почему}`);
      console.error('Ключ не сохранён: работать с непроверенным ключом хуже, чем не работать вовсе.');
      return 1;
    }
    записать({ ключ: готовый.trim(), имя: кто.имя, роль: кто.роль });
    console.log(`Вошли: ${кто.имя}${кто.роль ? ` · ${кто.роль}` : ''}`);
    console.log(`Ключ запомнен в ${где()}`);
    if (!согласился()) {
      console.log('\nЗапись обращений пока выключена. Включить — /vhod --согласие');
    }
    return 0;
  }

  // ---------- кто уже вошёл ----------

  const [названо, названныйКод] = доводы.filter((д) => !д.startsWith('--'));
  const н = прочитать();

  // Вошедшего не перерегистрируем: иначе в журнале заводится второй он же, и
  // след рвётся пополам — часть под одним ключом, часть под другим.
  if (н.ключ) {
    const кто = await опознать(н.ключ);
    if (!кто.опознан) {
      console.log(`Ключ есть, но войти не вышло: ${кто.почему}`);
      return 1;
    }
    console.log(`${кто.имя}${кто.роль ? ` · ${кто.роль}` : ''}`);
    console.log(`Запись обращений: ${согласился() ? 'включена' : 'выключена'}`);
    console.log(`Настройки: ${где()}`);
    return 0;
  }

  // ---------- регистрация ----------

  // ── Без имени — только показать, не заводить ─────────────────────────────
  // Раньше команда без доводов брала имя из git и тут же заводила участника.
  // Так проверка «кто я» становилась регистрацией: человек, забывший ключ,
  // спрашивал, вошёл ли он, и получал второго себя под логином из git —
  // навсегда, переименовать участника нельзя. Имя теперь ловит хук на ответе
  // «как вас зовут», а здесь без явного имени ничего не создаётся.
  const имя = названо;
  if (!имя) {
    const сам = самоимя();
    console.log('Вы не вошли.\n');
    console.log('Назовитесь — напишите Claude своё имя, ключ выпишется сам.');
    if (сам.имя) console.log(`Или командой: /vhod "${сам.имя}" — если так вас и зовут.`);
    console.log('Есть ключ: /vhod --ключ sorp_…');
    return 1;
  }

  // Код передаётся, если он есть. Открыт стенд или спрашивает код — решает
  // стенд; плагин про это не знает и знать не должен.
  const код = названныйКод || кодПриглашения();

  const о = await позвать('/register', {
    метод: 'POST',
    тело: код ? { name: имя, invite: код } : { name: имя },
  });
  const т = о.тело;

  if (!о.вышло) {
    console.error(`Не вышло: ${т.ошибка ?? о.почему ?? о.код}`);
    if (т.как_быть) console.error(т.как_быть);
    return 1;
  }

  записать({ ключ: т.ключ, имя: т.имя, роль: т.роль });

  console.log(`Готово. Вы — ${т.имя}${т.роль ? ` · ${т.роль}` : ''}`);
  console.log(`Ключ: ${т.ключ}`);
  console.log(`${т.предупреждение}\n`);
  console.log('─'.repeat(72));
  console.log('Плагин может записывать ваши вопросы в общий журнал разбора — тот, где');
  console.log('ведётся работа над процессами. Записываются только ваши вопросы, не ответы');
  console.log('Claude и не содержимое ваших файлов.');
  console.log('');
  console.log('Сейчас запись выключена. Включить, если вы не против:');
  console.log('  /vhod --согласие');
  console.log('─'.repeat(72));

  return 0;
}

process.exitCode = await главное();
