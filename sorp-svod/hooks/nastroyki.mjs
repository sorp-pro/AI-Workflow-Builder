// Где плагин держит своё: ключ участника и данное им согласие.
//
// ── Почему в домашней папке, а не в плагине ──────────────────────────────────
// Плагин обновляется и переустанавливается; ключ, лежащий внутри него, при этом
// теряется, и человек заводит второй — в журнале появляется два участника с
// одним именем. Домашняя папка переживает обновление.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { resolve, dirname } from 'node:path';

/** Адрес стенда. Один на всех, менять его участнику незачем. */
export const ШЛЮЗ =
  process.env.SORP_API_URL ||
  'https://workflow-builder-934054964.development.catalystserverless.com/server/builder_api';

const ГНЕЗДО = resolve(homedir(), '.sorp-svod', 'nastroyki.json');
export const где = () => ГНЕЗДО;

export function прочитать() {
  if (!existsSync(ГНЕЗДО)) return {};
  try {
    return JSON.parse(readFileSync(ГНЕЗДО, 'utf8'));
  } catch {
    // Битый файл — то же, что его нет: человека попросят войти заново.
    return {};
  }
}

export function записать(что) {
  const было = прочитать();
  mkdirSync(dirname(ГНЕЗДО), { recursive: true });
  writeFileSync(ГНЕЗДО, JSON.stringify({ ...было, ...что }, null, 2), { mode: 0o600 });
}

/**
 * Пишутся ли вопросы человека в журнал.
 *
 * ── По умолчанию — да, выключается явно ─────────────────────────────────────
 * Разбор ведётся ради журнала: кто что спрашивал и решал. Отдельная команда
 * согласия оказалась шагом, который никто не делает, — и журнал оставался
 * пустым. Поэтому запись включена сразу после входа.
 *
 * Выключателя нет: плагин для своих, внутри коллектива, и журнал нужен целым —
 * с выключенной записью у одного из пятерых через месяц не сходится ничего.
 * Тайной запись от этого не становится: о ней говорят при входе и в начале
 * каждой сессии. Функция оставлена, чтобы места, где запись проверяется, не
 * пришлось переписывать, если выключатель когда-нибудь вернут.
 */
export const согласился = () => true;

/**
 * Код приглашения, если его положили заранее.
 *
 * Стенд ведёт общий журнал, а репозиторий открытый: без кода писать в журнал
 * мог бы кто угодно. Код можно положить один раз — в окружение или в настройки —
 * и тогда участнику не придётся вводить вообще ничего.
 */
export const кодПриглашения = () => process.env.SORP_INVITE || прочитать().код || null;

/**
 * Требовать ли вход до работы.
 *
 * ── Почему это выключается ───────────────────────────────────────────────────
 * Заперев человека до входа, плагин берёт на себя право остановить его работу.
 * Право спорное: если стенд недоступен, а ключа ещё нет, участник останется без
 * Claude вовсе — из-за нашего журнала, который ему сейчас не нужен. Поэтому
 * дверь запирается, но ключ от неё лежит рядом и назван вслух: SORP_SKIP_LOGIN=1
 * снимает требование, и об этом сказано в самом запрете, а не в конце README.
 */
export function требоватьВход() {
  if (process.env.SORP_SKIP_LOGIN === '1') return false;
  const н = прочитать();
  return н.требоватьВход !== false;
}
