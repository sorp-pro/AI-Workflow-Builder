// В начале сессии — сказать, кто работает, или попросить назваться.
//
// Здесь же человек впервые узнаёт, что плагин записывает его вопросы. Не мелким
// шрифтом в конце README, а сразу: он ставит плагин, чтобы разбирать процессы,
// а не чтобы отдавать переписку, и должен решить это до, а не после.

import { прочитать, согласился, требоватьВход, ШЛЮЗ } from './nastroyki.mjs';
import { обновить } from './obnovlenie.mjs';

// Обновление — первым: если оно случилось, Claude должен узнать об этом
// вместе со всем остальным, в одном сообщении старта.
const обновилось = await обновить().catch(() => null);

const сказать = (текст) =>
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'SessionStart',
        additionalContext: обновилось ? обновилось + ' ' + текст : текст,
      },
    }),
  );

const н = прочитать();

if (!н.ключ && требоватьВход()) {
  // Имя ловит хук на следующей реплике и сам заводит ключ. Поэтому здесь нужно
  // ровно одно: чтобы Claude задал вопрос и не мешал человеку на него ответить
  // рассказом про хранилище, коды приглашения и устройство журнала.
  сказать(
    [
      '[SORP] Разбор процессов начинается со знакомства: до входа плагин не пропускает вопросы,',
      'потому что вопрос без автора через месяц никому ничего не говорит.',
      'Первым же сообщением спроси у человека, как его зовут, — одной короткой строкой, без объяснений',
      'про ключи, коды приглашения и устройство хранилища: всё это сделается само, когда он ответит.',
      'Ничего другого пока не делай и файлы не читай.',
      'Имя нужно с заглавной и не длиннее трёх слов — проверка строга нарочно: переименовать участника потом нельзя.',
      'Если его ответ не примут, попроси написать имя ещё раз, с заглавной буквы, и не пересказывай ему устройство проверки.',
      'Если он вместо имени спросит, зачем это, — ответь честно: имя нужно, чтобы в общем журнале разбора',
      'было видно, кто что спрашивал; запись самих вопросов при этом остаётся выключенной, пока он её не включит.',
    ].join(' '),
  );
} else if (!н.ключ) {
  сказать('[SORP] Участник не назван, но вход не требуется (SORP_SKIP_LOGIN). Работай как обычно, ничего не спрашивай.');
} else if (!согласился()) {
  сказать(
    [
      `[SORP] Участник ${н.имя} вошёл и выключил запись своих вопросов.`,
      'Его вопросы в журнал не пишутся. Это его решение, настаивать не нужно.',
      'Если он спросит, как включить обратно, — /sorp-svod:vhod --согласие.',
    ].join(' '),
  );
} else {
  сказать(
    [
      `[SORP] Работаешь с: ${н.имя}${н.роль ? `, роль — ${н.роль}` : ''}.`,
      'Вопросы этого человека и его выбор в вопросах с кнопками записываются в общий журнал разбора под его именем.',
      'Ответы не записываются, только вопросы.',
      `Стенд: ${ШЛЮЗ.replace(/^https?:\/\//, '').split('/')[0]}.`,
    ].join(' '),
  );
}
