// Стоит на входе каждой реплики и делает три разные вещи.
//
//   1. Ловит имя. Человека спросили, как его зовут, — он ответил обычной
//      репликой, и здесь она превращается в участника и ключ. Никаких команд:
//      называть себя человек умеет, а помнить «/vhod» — нет.
//   2. Не пускает неназвавшегося. Разбор ведётся сообща, и вопрос без автора
//      через месяц никому ничего не говорит.
//   3. Записывает вопрос — если человек на это согласился.
//
// ── Почему запрет и запись — разной строгости ────────────────────────────────
// Войти обязательно, отдавать переписку — нет. Слить их в одно значило бы
// получить согласие тем, что без него ничего не работает, то есть не получить
// его вовсе. И запись поэтому падает молча: плагин, ломающий работу из-за
// недоступной сети, снимут в первый же день — незаписанное обращение стоит
// одной строки, неработающий Claude стоит участника.

import { readFileSync, mkdirSync, statSync, rmSync, openSync, closeSync } from 'node:fs';
import { basename, dirname } from 'node:path';
import { прочитать, записать, где, согласился, требоватьВход, кодПриглашения, ШЛЮЗ } from './nastroyki.mjs';
import { позвать, похожеНаИмя } from './stend.mjs';

const подсказка = (строки) => ({
  hookSpecificOutput: { hookEventName: 'UserPromptSubmit', additionalContext: строки.join(' ') },
});

// ── Почему всё в функции ─────────────────────────────────────────────────────
// process.exit сразу после fetch валит Node ассерцией в libuv: сокет ещё
// закрывается. Хук при этом падает поверх собственного ответа.
async function главное() {
  let данные = {};
  try {
    данные = JSON.parse(readFileSync(0, 'utf8') || '{}');
  } catch {
    данные = {};
  }

  const вопрос = String(данные.prompt ?? '');
  const н = прочитать();

  // ---------- 1. кто ещё не назвался ----------

  // Сам вход запирать нельзя: иначе дверь заперта изнутри и войти нечем.
  // Установленный плагин называет свои команды с приставкой — /sorp-svod:vhod,
  // а не /vhod. Проверка знала только короткое имя и запирала собственную
  // команду входа: человек набирал её и не получал ничего, кроме отказа,
  // который приложение показывает едва заметно. Пропускаем обе формы и любую
  // команду плагина — каждая сама скажет, если без входа ей нечего делать.
  const проВход = /^\s*\/(?:(?:vhod|вход)\b|sorp-svod:)/i.test(вопрос);

  if (!н.ключ && требоватьВход() && !проВход) {
    // ── Почему не отказ, а подсказка ────────────────────────────────────────
    // Отказ хука каждое приложение показывает по-своему: терминал — строкой,
    // вкладка Code — едва заметно, Cowork — никак, там «Working on it» висит
    // без конца. Человек не знает, что его просят назваться, и не может даже
    // попросить Claude проверить, в чём дело: отказ глотает и эту просьбу.
    // Поэтому реплика доходит до Claude вместе с указанием — и объясняет он
    // словами, одинаково везде. Настоящую границу держит стенд: без ключа он
    // ничего не записывает, как бы Claude ни поступил.
    if (!похожеНаИмя(вопрос)) {
      return подсказка([
        '[SORP] Человек ещё не назвался, а разбор процессов ведётся под именем.',
        'Не выполняй его просьбу и не читай файлы. Ответь одной-двумя строками:',
        'попроси написать имя одной строкой, с заглавной, например «Мария Соколова», — ключ выпишется сам;',
        'если ключ у него уже есть — пусть наберёт /sorp-svod:vhod --ключ sorp_…',
        'Исключение одно: если он просит проверить связь со стендом или спрашивает, почему не получается войти, —',
        'помоги с этим, это часть входа.',
      ]);
    }

    const имя = вопрос.trim();

    // ── Замок на регистрацию ─────────────────────────────────────────────────
    // Плагин можно поставить и одновременно открыть его папку как проект —
    // тогда на одну реплику срабатывают два хука разом. Оба понесут имя на
    // стенд, второй получит «уже заведён» и заблокирует человека, который
    // только что вошёл. Кто взял замок — регистрирует; второй ждёт его ключ.
    const замок = где() + '.lock';
    mkdirSync(dirname(замок), { recursive: true });
    try {
      // Замок старше полуминуты — след упавшего хука, а не чужая работа.
      if (Date.now() - statSync(замок).mtimeMs > 30_000) rmSync(замок, { force: true });
    } catch {
      // Замка нет — так и должно быть.
    }
    let держу = false;
    try {
      closeSync(openSync(замок, 'wx'));
      держу = true;
    } catch {
      держу = false;
    }
    if (!держу) {
      for (let и = 0; и < 25; и++) {
        await new Promise((готово) => setTimeout(готово, 200));
        if (прочитать().ключ) return null;
      }
      return подсказка(['[SORP] Регистрация по этой реплике не успела закончиться. Попроси человека написать имя ещё раз.']);
    }

    // Код передаётся, если он есть: стенд может быть открыт, а может спрашивать
    // код — плагин про это не знает и знать не должен. Решает стенд, дело
    // плагина — донести то, что у человека есть.
    let о;
    try {
      // 6 секунд, а не 8: хук сам живёт 8, и ответ, пришедший к его смерти, никому не нужен.
      о = await позвать('/register', {
        метод: 'POST',
        ждать: 6000,
        тело: { name: имя, invite: кодПриглашения() || undefined },
      });
      if (о.вышло) записать({ ключ: о.тело.ключ, имя: о.тело.имя, роль: о.тело.роль });
    } finally {
      rmSync(замок, { force: true });
    }

    if (!о.вышло) {
      // Совет даём по делу: при занятом имени помогает назваться иначе, при
      // закрытой двери — нет, и предлагать это значит гонять человека по кругу.
      // Сеть — отдельный случай: в Cowork стенд закрыт, пока домен не
      // разрешён в настройках, и человеку нужно сказать именно это.
      const занято = о.код === 409;
      const нетСети = о.код === 0;
      return подсказка([
        `[SORP] Человек назвался «${имя}», но завести ему ключ не вышло: ${о.тело.ошибка ?? о.почему ?? о.код}.`,
        нетСети
          ? 'Скажи ему об этом прямо, одной-двумя строками.'
          : 'Скажи ему об этом прямо, одной-двумя строками, и больше ничего не делай.',
        ...(о.тело.как_быть ? [`Совет стенда: ${о.тело.как_быть}.`] : []),
        ...(занято ? ['Имя занято: пусть назовётся иначе или войдёт своим ключом — /sorp-svod:vhod --ключ sorp_….'] : []),
        ...(нетСети
          ? [
              `Стенд по сети недоступен. Проверь сам: curl -sS -m 10 ${ШЛЮЗ}/whoami — ответ с «ключ не опознан» значит,`,
              'что сеть в порядке. Если соединения нет и ты работаешь в Cowork или другой изолированной среде,',
              `объясни: домен ${new URL(ШЛЮЗ).host} нужно разрешить в Settings → Capabilities → Allow network egress`,
              '(для организации — Organization settings → Capabilities), затем начать новую сессию.',
            ]
          : []),
      ]);
    }

    // Реплику пропускаем дальше: для Claude это по-прежнему ответ на его вопрос
    // об имени, и ответить на него надо — но уже зная, кто перед ним.
    return подсказка([
      `[SORP] Человек назвался: ${о.тело.имя}${о.тело.роль ? `, роль — ${о.тело.роль}` : ''}.`,
      'Ключ выписан и запомнен, про вход спрашивать больше нечего.',
      `Скажи ему коротко: вошёл как ${о.тело.имя}, ключ — ${о.тело.ключ}, и его стоит сохранить:`,
      'в базе лежит только отпечаток, восстановить оттуда нельзя.',
      'Скажи и то, что его вопросы пока НЕ записываются в общий журнал, а включается это отдельно —',
      '/vhod --согласие. Не уговаривай включать: это его решение, и без него всё работает так же.',
      'Дальше сразу берись за разбор — выполни /razbor и веди человека по вопросам,',
      'ничего не переспрашивая про вход.',
    ]);
  }

  // ---------- 2. запись обращения ----------

  if (!н.ключ || !согласился()) return null;

  await позвать('/ask', {
    ключ: н.ключ,
    метод: 'POST',
    ждать: 4000,
    тело: {
      prompt: вопрос,
      session_id: данные.session_id ?? null,
      // Только имя папки проекта, не путь. Полный путь несёт имя учётной записи
      // и устройство чужого диска — ни то ни другое разбору не нужно, а README
      // обещает ровно «имя проекта». Обещание, которое код тихо превышает, хуже
      // отсутствия обещания: его проверят, и доверие кончится на первой строке.
      cwd: данные.cwd ? basename(String(данные.cwd)) : null,
      source: 'плагин',
    },
  });

  return null;
}

const ответ = await главное();
if (ответ) process.stdout.write(JSON.stringify(ответ));
