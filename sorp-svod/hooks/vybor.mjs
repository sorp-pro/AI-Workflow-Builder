// Записывает выбор человека в вопросах с кнопками.
//
// ── Почему отдельный хук ─────────────────────────────────────────────────────
// Когда Claude спрашивает кнопками, ответ человека приходит к нему не
// сообщением, а результатом инструмента AskUserQuestion. Хук на сообщения
// его не видит, и в журнале оставалась дыра ровно там, где человек принимал
// решение: вопрос Claude был, выбор — нет. Этот хук срабатывает после
// инструмента и кладёт в журнал пару «вопрос → что выбрано».
//
// Падает молча, как и запись сообщений: незаписанный выбор стоит строки
// журнала, сломанный ответ на вопрос — работы человека.

import { readFileSync } from 'node:fs';
import { basename } from 'node:path';
import { прочитать } from './nastroyki.mjs';
import { позвать } from './stend.mjs';

/**
 * Ответы из результата инструмента.
 *
 * Документация обещает ответы как { "текст вопроса": "выбранная метка" }, где
 * несколько меток идут через запятую, а «свой вариант» — текстом. Где именно
 * лежит этот объект в результате, не описано, поэтому ищем в обоих местах, а
 * если не нашли — пишем результат как есть: сырой выбор лучше потерянного.
 */
function ответы(данные) {
  const о = данные.tool_response;
  const кандидаты = [о?.answers, о?.result?.answers, данные.tool_input?.answers];
  for (const к of кандидаты) if (к && typeof к === 'object' && Object.keys(к).length) return к;
  return null;
}

async function главное() {
  let данные = {};
  try {
    данные = JSON.parse(readFileSync(0, 'utf8') || '{}');
  } catch {
    return;
  }
  if (данные.tool_name !== 'AskUserQuestion') return;

  const н = прочитать();
  if (!н.ключ) return;

  const вопросы = данные.tool_input?.questions || [];
  const выбор = ответы(данные);

  const строки = выбор
    ? Object.entries(выбор).map(([вопрос, ответ]) => {
        const заголовок = вопросы.find((в) => в.question === вопрос)?.header;
        return `${заголовок ? `[${заголовок}] ` : ''}${вопрос} → ${ответ}`;
      })
    : [
        ...вопросы.map((в) => `${в.header ? `[${в.header}] ` : ''}${в.question}`),
        `→ ${JSON.stringify(данные.tool_response ?? null).slice(0, 2000)}`,
      ];

  if (!строки.length) return;

  await позвать('/ask', {
    ключ: н.ключ,
    метод: 'POST',
    ждать: 4000,
    тело: {
      prompt: строки.join('\n'),
      session_id: данные.session_id ?? null,
      cwd: данные.cwd ? basename(String(данные.cwd)) : null,
      source: 'выбор',
    },
  });
}

await главное().catch(() => {});
