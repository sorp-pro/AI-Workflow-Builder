// Пускает в работу только названного человека и записывает его вопрос —
// если он на это согласился.
//
// ── Две разные строгости ─────────────────────────────────────────────────────
// Вход обязателен: разбор ведётся сообща, и вопрос без автора через месяц никому
// ничего не говорит. Запись обращений — нет: человек может разбирать процессы и
// не отдавать переписку. Слить их в одно значило бы получить согласие тем, что
// без него не работает, — то есть не получить его вовсе.
//
// Запись падает молча. Плагин, ломающий работу из-за недоступной сети, снимут в
// первый же день: незаписанное обращение стоит одной строки, неработающий
// Claude — участника.

import { readFileSync } from 'node:fs';
import { прочитать, согласился, требоватьВход, ШЛЮЗ } from './nastroyki.mjs';

let данные = {};
try {
  данные = JSON.parse(readFileSync(0, 'utf8') || '{}');
} catch {
  данные = {};
}

const вопрос = String(данные.prompt ?? '');

/**
 * Сам вход запирать нельзя.
 *
 * Иначе получается дверь, запертая изнутри: чтобы войти, нужно выполнить
 * команду, а команду не пропускает требование входа. Так же пропускаем разговор
 * о самом входе — человек, спрашивающий «как войти», уже делает то, что нужно.
 */
const проСебя = /^\s*\/(vhod|вход)\b/i.test(вопрос) || /\b(войти|вход|ключ|токен|регистрац)/i.test(вопрос);

const н = прочитать();

if (!н.ключ && требоватьВход() && !проСебя) {
  process.stdout.write(
    JSON.stringify({
      decision: 'block',
      reason: [
        'Разбор процессов ведётся под именем: вопрос без автора через месяц никому ничего не скажет.',
        '',
        'Назовитесь — это одна команда:',
        '',
        '    /vhod',
        '',
        'Имя подставится ваше, ключ выпишет стенд. Если у вас уже есть ключ — /vhod --ключ sorp_…',
        '',
        'Запись ваших вопросов при этом останется выключенной, пока вы сами её не включите.',
        'Работать без входа: SORP_SKIP_LOGIN=1 в окружении.',
      ].join('\n'),
    }),
  );
  process.exit(0);
}

// Ключа нет, но входа не требуем, либо нет согласия — выходим молча.
if (!н.ключ || !согласился()) process.exit(0);

// Таймер гасится вручную: AbortSignal.timeout оставляет живой хендл, и выход
// поверх него роняет Node на Windows с assertion в libuv.
const сторож = new AbortController();
const будильник = setTimeout(() => сторож.abort(), 4000);

try {
  await fetch(ШЛЮЗ.replace(/\/$/, '') + '/ask', {
    method: 'POST',
    signal: сторож.signal,
    headers: { 'Content-Type': 'application/json', 'X-Builder-Key': н.ключ },
    body: JSON.stringify({
      prompt: вопрос,
      session_id: данные.session_id ?? null,
      cwd: данные.cwd ?? null,
      source: 'плагин',
    }),
  });
} catch {
  // Сеть недоступна — обращение потеряно, работа продолжается.
} finally {
  clearTimeout(будильник);
}
