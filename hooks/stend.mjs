// Разговор со стендом: один способ позвать, один способ не дождаться.
//
// ── Почему таймер гасится вручную ────────────────────────────────────────────
// AbortSignal.timeout оставляет живой хендл, и выход поверх него роняет Node на
// Windows ассерцией в libuv. Человек видит краш вместо своего ответа.

import { ШЛЮЗ } from './nastroyki.mjs';

export async function позвать(путь, { ключ = null, метод = 'GET', тело = null, ждать = 8000 } = {}) {
  const сторож = new AbortController();
  const будильник = setTimeout(() => сторож.abort(), ждать);
  try {
    const о = await fetch(ШЛЮЗ.replace(/\/$/, '') + путь, {
      method: метод,
      signal: сторож.signal,
      headers: {
        ...(тело ? { 'Content-Type': 'application/json; charset=utf-8' } : {}),
        ...(ключ ? { 'X-Builder-Key': ключ } : {}),
      },
      ...(тело ? { body: JSON.stringify(тело) } : {}),
    });
    const т = await о.json().catch(() => ({}));
    return { вышло: о.ok, код: о.status, тело: т };
  } catch (е) {
    return { вышло: false, код: 0, тело: {}, почему: `стенд недоступен: ${е.message}` };
  } finally {
    clearTimeout(будильник);
  }
}

/**
 * Похоже ли это на имя человека.
 *
 * ── Зачем проверять ──────────────────────────────────────────────────────────
 * Имя ловится из обычной реплики: человека спросили, как его зовут, и что он
 * ответит — неизвестно. Ответить он может и вопросом по делу. Записать вопрос
 * как имя участника — значит завести в журнале «а можно посмотреть шаг 3?» и
 * закрепить это за ним навсегда: переименовать участника нельзя, только завести
 * второго, разорвав след пополам.
 */
export function похожеНаИмя(текст) {
  const т = String(текст || '').trim();
  if (т.length < 2 || т.length > 60) return false;
  if (т.includes('\n')) return false;
  if (т.startsWith('/')) return false;
  if (/[?？]/.test(т)) return false;
  if (т.split(/\s+/).length > 4) return false;
  // Имя состоит из букв, дефисов и точек. Скобки, слэши, цифры — это уже не имя.
  return /^[\p{L}][\p{L}\s.'’-]*$/u.test(т);
}
