// Разговор со стендом: один способ позвать, один способ не дождаться.
//
// ── Почему таймер гасится вручную ────────────────────────────────────────────
// AbortSignal.timeout оставляет живой хендл, и выход поверх него роняет Node на
// Windows ассерцией в libuv. Человек видит краш вместо своего ответа.

import { ШЛЮЗ } from './nastroyki.mjs';

export async function позвать(путь, { ключ = null, метод = 'GET', тело = null, ждать = 8000 } = {}) {
  const сторож = new AbortController();
  const будильник = setTimeout(() => сторож.abort(), ждать);
  try {
    const о = await fetch(ШЛЮЗ.replace(/\/$/, '') + путь, {
      method: метод,
      signal: сторож.signal,
      headers: {
        ...(тело ? { 'Content-Type': 'application/json; charset=utf-8' } : {}),
        ...(ключ ? { 'X-Builder-Key': ключ } : {}),
      },
      ...(тело ? { body: JSON.stringify(тело) } : {}),
    });
    const т = await о.json().catch(() => ({}));
    return { вышло: о.ok, код: о.status, тело: т };
  } catch (е) {
    return { вышло: false, код: 0, тело: {}, почему: `стенд недоступен: ${е.message}` };
  } finally {
    clearTimeout(будильник);
  }
}

/**
 * Слова, с которых начинают не имя, а разговор.
 *
 * Список короткий и не претендует на полноту: он ловит частое, а всё остальное
 * ловит проверка заглавных ниже. Двойная сеть здесь дешевле одной ошибки.
 */
const НЕ_ИМЯ = new Set([
  'покажи', 'расскажи', 'сделай', 'дай', 'давай', 'помоги', 'открой', 'найди',
  'что', 'чего', 'как', 'какой', 'какие', 'где', 'когда', 'почему', 'зачем',
  'кто', 'куда', 'сколько', 'можно', 'нужно', 'хочу', 'надо', 'привет',
  'здравствуйте', 'да', 'нет', 'ок', 'ладно', 'спасибо', 'слушай', 'а',
]);

/**
 * Похоже ли это на имя человека.
 *
 * ── Зачем проверять так строго ───────────────────────────────────────────────
 * Имя ловится из обычной реплики: человека спросили, как его зовут, и что он
 * ответит — неизвестно. Ответить он может и вопросом по делу. Записать вопрос
 * как имя участника — значит завести в журнале «покажи процесс гипотез» и
 * закрепить это за ним навсегда: переименовать участника нельзя, только завести
 * второго, разорвав след пополам.
 *
 * Поэтому проверка нарочно перегибает в отказ. Ошибиться можно в две стороны:
 * не узнать имя — человека переспросят, он ответит ещё раз; принять за имя
 * фразу — и это уже не исправить. Цена этих ошибок несопоставима.
 */
export function похожеНаИмя(текст) {
  const т = String(текст || '').trim();
  if (т.length < 2 || т.length > 60) return false;
  if (т.includes('\n')) return false;
  if (/[?？!/@#№$%^&*(){}[\]<>|\\=+_0-9]/.test(т)) return false;

  const слова = т.split(/\s+/);
  if (слова.length > 3) return false;
  if (НЕ_ИМЯ.has(слова[0].toLowerCase())) return false;

  // Имя пишут с заглавной. «Мария Соколова» — имя, «покажи процесс гипотез» —
  // нет, и различает их ровно это: во фразе с заглавной только первое слово.
  // Части двойных имён и фамилий считаются отдельно: в «Анна-Мария» и «О’Коннор»
  // заглавная стоит и после чёрточки.
  const частьИмени = (ч) => /^\p{Lu}[\p{Ll}.]*$/u.test(ч);
  return слова.every((с) => с.split(/[-'’]/).every(частьИмени));
}
