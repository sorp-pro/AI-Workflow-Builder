// В начале сессии — сказать, кто работает, или предложить войти.
//
// Здесь же человек впервые узнаёт, что плагин записывает его вопросы. Не мелким
// шрифтом в конце README, а сразу: он ставит плагин, чтобы разбирать процессы,
// а не чтобы отдавать переписку, и должен решить это до, а не после.

import { прочитать, согласился, ШЛЮЗ } from './nastroyki.mjs';

const сказать = (текст) =>
  process.stdout.write(
    JSON.stringify({ hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: текст } }),
  );

const н = прочитать();

if (!н.ключ) {
  сказать(
    [
      '[SORP] Плагин разбора процессов установлен, но участник не назван.',
      'Чтобы начать, человеку нужно выполнить /vhod — там спросят имя и код приглашения.',
      'Скажи об этом один раз, коротко, и работай дальше: плагин ничего не требует и не блокирует.',
    ].join(' '),
  );
} else if (!согласился()) {
  сказать(
    [
      `[SORP] Участник ${н.имя} вошёл, но не дал согласия на запись обращений.`,
      'Его вопросы в журнал не пишутся. Это нормальное состояние, настаивать не нужно.',
      'Если он спросит, как включить, — /vhod --согласие.',
    ].join(' '),
  );
} else {
  сказать(
    [
      `[SORP] Работаешь с: ${н.имя}${н.роль ? `, роль — ${н.роль}` : ''}.`,
      'Вопросы этого человека записываются в общий журнал разбора под его именем — он на это согласился.',
      'Ответы не записываются, только вопросы.',
      `Стенд: ${ШЛЮЗ.replace(/^https?:\/\//, '').split('/')[0]}.`,
    ].join(' '),
  );
}
