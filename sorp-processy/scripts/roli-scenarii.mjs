// Сценарии по ролям: проверяем не маршрут, а людей за столами.
//
//   node roli-scenarii.mjs              все процессы
//   node roli-scenarii.mjs PROC-012     один
//   node roli-scenarii.mjs --json
//
// Обычный прогон проверяет, что шаг делает нужный стол. Здесь проверяется то, что ломается на
// практике: за столом сидит человек, у него есть замещающий, он может совмещать два стола, а
// рядом есть смежный стол, который «по-соседски» возьмётся за чужой шаг. Виртуальные
// пользователи выводятся из карточек ролей (roli/DESK-xxx.json, скрипт roli.mjs), а сценарии —
// из моделей процессов.
//
//   смежный стол   шаг делает стол, который работает в этом же процессе, но не на этом шаге;
//   замещающий     шаг делает врио или дублёр стола — модель должна либо знать замещение,
//                  либо честно его не пустить;
//   совмещение     два шага, которые нельзя делать одному человеку, делает один человек;
//   день роли      все шаги одного стола в процессе подряд — видно, что стол делает за день.
//
// Итог — vyhod/processy/roli-progon.json и находки в консоль. Находка — не всегда ошибка
// модели: «замещение не описано» значит, что источник молчит, и это вопрос людям.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { индекс, прогнать, оценить } from './dvizhok.mjs';
import { МОДЕЛИ, ВЫХОД, путь, напрямую } from './mesto.mjs';

const КАРТОЧКИ = путь('roli');
const копия = (x) => JSON.parse(JSON.stringify(x));

/** Виртуальные пользователи стола из карточки роли. */
export function пользователи(код) {
  const ф = path.join(КАРТОЧКИ, `${код}.json`);
  if (!existsSync(ф)) return [];
  const к = JSON.parse(readFileSync(ф, 'utf8'));
  const имя = (s) => String(s || '').split(/[·;,(]/)[0].trim();
  const out = [{ вид: 'основной', desk: код, кто: имя(к.кто.за_столом) || `оператор ${код}`, источник: к.кто.за_столом ? 'карта: кто за столом' : 'имени в карте нет' }];
  if (к.кто.врио) out.push({ вид: 'замещающий', desk: код, кто: имя(к.кто.врио.кто), источник: `карта: врио · ${к.кто.врио.основание || ''}`.trim() });
  if (к.кто.дублёр) out.push({ вид: 'дублёр', desk: код, кто: имя(к.кто.дублёр), источник: 'карта: дублёр', столы: [...String(к.кто.дублёр).matchAll(/DESK-\d{3}/g)].map((m) => m[0]) });
  for (const с of к.кто.совмещения || []) {
    const [человек, столы] = String(с).split(':');
    out.push({ вид: 'совмещающий', desk: код, кто: имя(человек), столы: [...String(столы).matchAll(/DESK-\d{3}/g)].map((m) => m[0]), источник: 'карта: один человек за несколькими столами' });
  }
  return out;
}

/** Пары столов, для которых в модели записано решение «совмещение допустимо». */
function совмещениеРазрешено(модель) {
  const пары = new Set();
  for (const а of модель.assumptions || []) {
    const т = String(а.taken || '');
    if (!/совмещение столов .* допустимо/i.test(т)) continue;
    const столы = [...т.matchAll(/DESK-\d{3}/g)].map((m) => m[0]).sort();
    if (столы.length >= 2) пары.add(столы.slice(0, 2).join('+'));
  }
  return пары;
}

export function сценарииРолей(модель, карточки) {
  const И = индекс(модель);
  const разрешено = совмещениеРазрешено(модель);
  const пути = модель.paths || [];
  const база = пути[0]?.events;
  if (!база?.length) return [];
  const шагиПути = [...new Set(база.map((e) => e.step).filter(Boolean))];
  const столыШагов = new Map(модель.steps.map((s) => [s.key, [s.desk, ...(s.desks || [])].filter(Boolean)]));
  const всеСтолы = [...new Set([...столыШагов.values()].flat())];
  const список = [];
  const add = (группа, имя, события, ждём, про) => список.push({ группа, имя, события, ждём, про });

  for (const [i, e] of база.entries()) {
    if (!e.step) continue;
    const свои = столыШагов.get(e.step) || [];
    const стол = свои[0];
    if (!стол) continue;
    const карточка = карточки.get(стол);

    // Смежный стол: работает в этом процессе, но не на этом шаге.
    const сосед = всеСтолы.find((к) => !свои.includes(к));
    if (сосед) add('смежный стол', `${e.step}: за шаг берётся ${сосед} — смежный стол процесса`, база.map((x, j) => (j === i ? { ...x, desk: сосед, actor: `оператор ${сосед}` } : x)), 'поймать', `${стол}→${сосед}`);

    // Замещающий и дублёр: человек другого стола делает шаг по замещению.
    for (const п of (пользователи(стол) || []).filter((u) => u.вид === 'замещающий' || u.вид === 'дублёр')) {
      const чужойСтол = (п.столы || []).find((к) => !свои.includes(к));
      if (!чужойСтол) continue;
      add('замещение', `${e.step}: шаг делает ${п.вид} ${п.кто} со стола ${чужойСтол}`, база.map((x, j) => (j === i ? { ...x, desk: чужойСтол, actor: п.кто } : x)), 'поймать', `${стол}←${чужойСтол}`);
    }

    // Совмещение: один человек за двумя столами делает оба шага.
    for (const п of (карточка?.совмещающие || [])) {
      const другой = (п.столы || []).find((к) => к !== стол && всеСтолы.includes(к));
      if (!другой) continue;
      // Нарушение возможно, только если второй шаг делает именно другой стол пары.
      const шагДругого = база.find((x) => x.step && (столыШагов.get(x.step) || [])[0] === другой);
      if (!шагДругого || шагДругого.step === e.step) continue;
      const нов = копия(база);
      for (const x of нов) if (x.step === e.step || x.step === шагДругого.step) x.actor = п.кто;
      const парой = [стол, другой].sort().join('+');
      const ждём = разрешено.has(парой) ? (пути[0].expect || 'чисто') : 'поймать';
      add('совмещение', `${e.step} и ${шагДругого.step} делает один человек — ${п.кто} (${стол} и ${другой})${разрешено.has(парой) ? ' — совмещение разрешено решением' : ''}`, нов, ждём, `${стол}+${другой}`);
    }
  }

  // День роли: сколько шагов процесса приходится на один стол.
  for (const стол of всеСтолы) {
    const свои = шагиПути.filter((s) => (столыШагов.get(s) || []).includes(стол));
    if (свои.length < 2) continue;
    add('день роли', `${стол}: ${свои.length} шагов процесса за день — ${свои.join(', ')}`, база, пути[0].expect || 'чисто', стол);
  }
  return список;
}

export function прогнатьРоли(модель, карточки) {
  const И = индекс(модель);
  const сц = сценарииРолей(модель, карточки);
  const итог = { proc: модель.process?.id, всего: сц.length, поГруппам: {}, находки: [] };
  for (const с of сц) {
    const { журнал } = прогнать(модель, с.события, И);
    const о = оценить(с, журнал);
    const г = (итог.поГруппам[с.группа] ||= { всего: 0 });
    г.всего++; г[о.вердикт] = (г[о.вердикт] || 0) + 1;
    const ждали = с.ждём === 'поймать' ? ['поймано'] : ['чисто', 'сигнал'];
    if (!ждали.includes(о.вердикт)) {
      итог.находки.push({ группа: с.группа, сценарий: с.имя, ждали: с.ждём, вердикт: о.вердикт, первое: о.первое ? { step: о.первое.step, итог: о.первое.итог, правило: о.первое.правило, текст: о.первое.текст || о.первое.вопрос } : null });
    }
  }
  return итог;
}

if (напрямую(import.meta.url)) {
  const арг = process.argv.slice(2);
  const один = арг.find((x) => /^PROC-\d{3}$/.test(x));
  const карточки = new Map();
  if (existsSync(КАРТОЧКИ)) for (const ф of readdirSync(КАРТОЧКИ).filter((f) => /^DESK-\d{3}\.json$/.test(f))) {
    const к = JSON.parse(readFileSync(path.join(КАРТОЧКИ, ф), 'utf8'));
    карточки.set(к.desk, { ...к, совмещающие: пользователи(к.desk).filter((u) => u.вид === 'совмещающий') });
  }
  const итоги = [];
  for (const ф of readdirSync(МОДЕЛИ).filter((f) => /^PROC-\d{3}\.json$/.test(f) && (!один || f === `${один}.json`)).sort()) {
    итоги.push(прогнатьРоли(JSON.parse(readFileSync(path.join(МОДЕЛИ, ф), 'utf8')), карточки));
  }
  writeFileSync(path.join(ВЫХОД, 'roli-progon.json'), JSON.stringify({ когда: new Date().toISOString(), итоги }, null, 1));
  if (арг.includes('--json')) { process.stdout.write(JSON.stringify(итоги, null, 1)); process.exit(0); }
  const всего = итоги.reduce((a, x) => a + x.всего, 0);
  const группы = {};
  for (const и of итоги) for (const [г, v] of Object.entries(и.поГруппам)) { группы[г] = группы[г] || { всего: 0, поймано: 0 }; группы[г].всего += v.всего; группы[г].поймано += v.поймано || 0; }
  console.log(`Сценариев по ролям: ${всего} на ${итоги.length} процессов`);
  for (const [г, v] of Object.entries(группы)) console.log(`  ${г.padEnd(14)} всего ${String(v.всего).padStart(4)} · поймано ${String(v.поймано).padStart(4)}`);
  const находки = итоги.flatMap((и) => и.находки.map((н) => ({ ...н, proc: и.proc })));
  console.log(`Находок (ждали одно, вышло другое): ${находки.length}`);
  for (const н of находки.slice(0, 20)) console.log(`  ✗ ${н.proc} · ${н.группа} · ждали «${н.ждали}», вышло «${н.вердикт}» · ${н.сценарий}`);
  console.log(`Итог: ${path.join(ВЫХОД, 'roli-progon.json')}`);
}
