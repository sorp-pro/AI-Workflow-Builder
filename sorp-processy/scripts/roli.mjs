// Карточки ролей: что известно про каждый рабочий стол — из карты и из моделей процессов.
//
//   node roli.mjs                     карточки всех столов, занятых в моделях
//   node roli.mjs DESK-013            один стол
//   node roli.mjs --probely           только чего не хватает, сводкой
//
// Пишет в рабочую папку: roli/DESK-xxx.json (машине) и roli/DESK-xxx.md (человеку),
// плюс roli/_svod.md — сводка по всем столам.
//
// Карточка — не новая правда, а сбор того, что уже есть: паспорт стола карты (задача, права,
// каталог решений, кто за столом, врио, дублёр) и работа стола в моделях (шаги: получил →
// сделал → сдал, сроки, отказы, визы, сигналы). Чего в источниках нет — «Ритм» и «Практика»:
// объём, пики, отсечки, типичные ошибки. Это собирают у людей за столом, и карточка прямо
// говорит, что там пусто.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { МОДЕЛИ, карта, путь, напрямую } from './mesto.mjs';

const ВЫХОД = путь('roli');
const мм = карта();
const столКарты = new Map(мм.desks.map((d) => [d.id, d]));
const процессКарты = new Map(мм.procs.map((p) => [p.id, p]));
const строка = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const непусто = (s) => строка(s) && !/^(не задано|не назван\w*|нет|—|-)$/i.test(строка(s));

/** Люди из поля «кто за столом»: имена с большой буквы, чтобы найти совмещения. */
const люди = (s) => [...new Set([...String(s || '').matchAll(/([А-ЯЁ][а-яё]+(?:\s+[А-ЯЁ][а-яё]+)?)/g)].map((m) => m[1]).filter((x) => !/^(Стол|Вакансия|Врио|После|На|Куратор|Приоритет|Октябрь)$/i.test(x)))];

/** Работа стола во всех моделях процессов. */
function изМоделей() {
  const по = new Map();
  const взять = (код) => { if (!по.has(код)) по.set(код, { шаги: [], визы: [], сигналы: [], процессы: new Set() }); return по.get(код); };
  for (const ф of readdirSync(МОДЕЛИ).filter((f) => /^PROC-\d{3}\.json$/.test(f))) {
    const м = JSON.parse(readFileSync(path.join(МОДЕЛИ, ф), 'utf8'));
    const proc = ф.slice(0, 8);
    const поле = new Map((м.fields || []).map((f) => [f.key, f]));
    for (const s of м.steps || []) {
      for (const код of [s.desk, ...(s.desks || [])].filter(Boolean)) {
        const к = взять(код); к.процессы.add(proc);
        к.шаги.push({
          proc, title: м.process?.title, step: s.key, no: s.no, action: s.action,
          получил: s.entry ?? null, сдал: s.fact ?? null,
          срок: s.deadline ? JSON.stringify(s.deadline) : (s.deadline_min != null ? `${s.deadline_min} мин` : null),
          решение: s.decision ? `${s.decision.title}: ${(s.decision.options || []).join(' / ')}` : null,
          полей: (s.fields || []).length,
          пишет: (s.fields || []).filter((x) => x.role !== 'читает').map((x) => поле.get(x.field)?.label || x.field).slice(0, 12),
          отказ: (м.rules || []).filter((r) => r.step === s.key && r.on_fail).map((r) => ({ правило: r.id, текст: строка(r.on_fail.text || r.id), кому: [].concat(r.on_fail.to || []).filter(Boolean) })),
        });
      }
      for (const п of s.fields || []) if (п.by_desk) for (const код of [].concat(п.by_desk)) { const к = взять(код); к.процессы.add(proc); к.визы.push({ proc, step: s.key, поле: поле.get(п.field)?.label || п.field }); }
    }
    for (const r of м.rules || []) for (const код of [].concat(r.on_fail?.to || []).filter((x) => typeof x === 'string' && /^DESK-\d{3}$/.test(x))) { const к = взять(код); к.процессы.add(proc); к.сигналы.push({ proc, правило: r.id, что: строка(r.on_fail.text || r.id) }); }
    for (const t of м.timers || []) for (const код of [].concat(t.to || []).filter((x) => typeof x === 'string' && /^DESK-\d{3}$/.test(x))) { const к = взять(код); к.процессы.add(proc); к.сигналы.push({ proc, правило: t.id || 'таймер', что: строка(t.text || 'таймер') }); }
  }
  return по;
}

function карточка(код, работа, совмещения) {
  const d = столКарты.get(код) || {};
  const f = d.fields || {};
  const роли = мм.lpd.filter((x) => x.d === код);
  const кто = {
    за_столом: непусто(d.who) ? строка(d.who) : null,
    по_умолчанию: непусто(d.who_default) ? строка(d.who_default) : null,
    вакансия: d.vacant === true || /вакан/i.test(String(d.vac_note || '')),
    заметка_кадры: непусто(d.vac_note) ? строка(d.vac_note) : null,
    врио: непусто(d.vrio) ? { кто: строка(d.vrio), вид: строка(d.vrio_kind), с: строка(d.vrio_s), основание: строка(d.vrio_src) } : null,
    дублёр: непусто(d.dubler) ? строка(d.dubler) : null,
    один_человек: d.single === true || null,
    руководитель: непусто(d.ruk) ? строка(d.ruk) : null,
    совмещения: совмещения.length ? совмещения : null,
  };
  const права = {
    задача: непусто(f['Задача стола']) ? строка(f['Задача стола']) : null,
    принимает: непусто(f['Принимает']) ? строка(f['Принимает']) : null,
    возвращает: непусто(f['Возвращает фактом']) ? строка(f['Возвращает фактом']) : null,
    сроки_реакции: непусто(f['Сроки реакции']) ? строка(f['Сроки реакции']) : null,
    показатели: непусто(f['Показатели']) ? строка(f['Показатели']) : null,
    видит: непусто(d.prava?.vidit) ? строка(d.prava.vidit) : null,
    создаёт: непусто(d.prava?.sozdaet) ? строка(d.prava.sozdaet) : null,
    изменяет: непусто(d.prava?.menyaet) ? строка(d.prava.menyaet) : null,
    утверждает: непусто(d.prava?.utverzhdaet) ? строка(d.prava.utverzhdaet) : null,
    удаление: непусто(d.prava?.udalenie) ? строка(d.prava.udalenie) : null,
    красная_зона: Array.isArray(d.prava?.krasnaya_zona) ? d.prava.krasnaya_zona.map((x) => строка(typeof x === "string" ? x : [x.a, x.w, x.kod].filter(Boolean).join(" · ") || JSON.stringify(x))).join(" | ") : (непусто(d.prava?.krasnaya_zona) ? строка(d.prava.krasnaya_zona) : null),
    каталог_решений: (d.kat || []).map((k) => ({ код: k.kod, действие: строка(k.a), кто_решает: строка(k.w), форма: строка(k.f), вид: строка(k.vid), основание: строка(k.s) })),
    лимиты_числом: [...new Set((d.kat || []).flatMap((k) => [...String(`${k.a} ${k.f} ${k.s}`).matchAll(/(\d[\d\s]{0,9}\d|\d)\s*(AED|дирхам\p{L}*|%)/giu)].map((m) => строка(m[0]))))],
  };
  const вПроцессах = [...new Set([...работа.процессы, ...роли.map((r) => r.p)])].sort().map((p) => ({
    proc: p, название: процессКарты.get(p)?.n ?? null,
    роли_карты: роли.filter((r) => r.p === p).map((r) => строка(r.role)),
    шагов: работа.шаги.filter((s) => s.proc === p).length,
    виз: работа.визы.filter((s) => s.proc === p).length,
    сигналов: работа.сигналы.filter((s) => s.proc === p).length,
  }));
  const пробелы = [];
  if (!кто.за_столом) пробелы.push('кто за столом не назван');
  if (!кто.руководитель) пробелы.push('руководитель стола не назван');
  if (кто.вакансия) пробелы.push('вакансия');
  if (!кто.дублёр && !кто.врио) пробелы.push('нет ни врио, ни дублёра');
  if (!права.лимиты_числом.length) пробелы.push('лимиты полномочий числами не заданы');
  if (!кто.совмещения) пробелы.push('совмещения не описаны (допустимые и недопустимые)');
  const неподтверждённые = роли.filter((r) => !r.status || /черновик|источника нет/i.test(String(r.status) + String(r.role)));
  if (неподтверждённые.length) пробелы.push(`роли в процессах не подтверждены: ${неподтверждённые.length} из ${роли.length}`);
  пробелы.push('ритм не собран (объём, пики, отсечки)', 'практика не собрана (ошибки, споры, исключения)');

  return {
    desk: код, название: строка(d.hname || d.name || код), единица: строка(d.un), контур: строка(d.contour), тип: строка(d.type),
    редакция_карты: мм.version?.red ?? null, собрано: new Date().toISOString().slice(0, 10),
    кто, права, роли_в_процессах: вПроцессах,
    работа: { шаги: работа.шаги, визы: работа.визы, сигналы: работа.сигналы },
    ритм: { объём: null, пики: null, отсечки: null, закрытие: null, пометка: 'собирается у людей за столом' },
    практика: { ошибки: null, споры: null, исключения: null, пометка: 'собирается у людей за столом' },
    пробелы,
  };
}

function вМД(к) {
  const с = [`# ${к.desk} · ${к.название}`, '', `Карта ${к.редакция_карты} · собрано ${к.собрано} · единица: ${к.единица || '—'} · контур: ${к.контур || '—'} · тип стола: ${к.тип || '—'}`, '', '## 1. Кто', '', '| Что | Значение |', '|---|---|'];
  const строки = [['За столом', к.кто.за_столом], ['По умолчанию', к.кто.по_умолчанию], ['Вакансия', к.кто.вакансия ? 'да' : null], ['Заметка кадров', к.кто.заметка_кадры], ['Врио', к.кто.врио && `${к.кто.врио.кто}${к.кто.врио.вид ? ` · ${к.кто.врио.вид}` : ''}${к.кто.врио.с ? ` · с ${к.кто.врио.с}` : ''}`], ['Дублёр', к.кто.дублёр], ['Один человек на столе', к.кто.один_человек ? 'да' : null], ['Руководитель', к.кто.руководитель], ['Совмещения', к.кто.совмещения && к.кто.совмещения.join('; ')]];
  for (const [а, б] of строки) if (б) с.push(`| ${а} | ${б} |`);
  с.push('', '## 2. Права', '');
  if (к.права.задача) с.push(`**Задача стола.** ${к.права.задача}`, '');
  for (const [и, в] of [['Принимает', к.права.принимает], ['Возвращает фактом', к.права.возвращает], ['Сроки реакции', к.права.сроки_реакции], ['Показатели', к.права.показатели], ['Видит', к.права.видит], ['Создаёт', к.права.создаёт], ['Изменяет', к.права.изменяет], ['Утверждает', к.права.утверждает], ['Удаление', к.права.удаление], ['Красная зона', к.права.красная_зона]]) if (в) с.push(`- **${и}:** ${в}`);
  if (к.права.лимиты_числом.length) с.push('', `**Лимиты числом из каталога решений:** ${к.права.лимиты_числом.join(' · ')}`);
  if (к.права.каталог_решений.length) {
    с.push('', '### Каталог решений', '', '| Код | Решение | Кто решает | Форма | Вид |', '|---|---|---|---|---|');
    for (const r of к.права.каталог_решений) с.push(`| ${r.код || '—'} | ${r.действие} | ${r.кто_решает || '—'} | ${r.форма || '—'} | ${r.вид || '—'} |`);
  }
  с.push('', '## 3. Роли в процессах', '', '| Процесс | Роль по карте | Шагов | Виз | Сигналов |', '|---|---|---:|---:|---:|');
  for (const p of к.роли_в_процессах) с.push(`| ${p.proc} · ${p.название || ''} | ${p.роли_карты.join('; ') || '—'} | ${p.шагов} | ${p.виз} | ${p.сигналов} |`);
  if (к.работа.шаги.length) {
    с.push('', '### Шаги: получил → сделал → сдал', '', '| Процесс | Шаг | Получил | Сделал | Сдал | Срок | Отказ кому |', '|---|---|---|---|---|---|---|');
    for (const s of к.работа.шаги) с.push(`| ${s.proc} | ${s.no}. ${s.action} | ${(s.получил || '—').slice(0, 90)} | пишет ${s.полей} полей${s.решение ? `; ${s.решение}` : ''} | ${(s.сдал || '—').slice(0, 90)} | ${s.срок || '—'} | ${[...new Set(s.отказ.flatMap((o) => o.кому))].join(', ') || '—'} |`);
  }
  с.push('', '## 4. Ритм', '', 'Собирается у людей за столом.', '', '| Показатель | Значение |', '|---|---|', '| Объём | `null` |', '| Пики | `null` |', '| Отсечки | `null` |', '| Закрытие дня или периода | `null` |');
  с.push('', '## 5. Практика', '', 'Собирается у людей за столом.', '', '| Показатель | Значение |', '|---|---|', '| Типичные ошибки | `null` |', '| Споры | `null` |', '| Исключения | `null` |');
  с.push('', '## Чего не хватает', '', ...к.пробелы.map((п) => `- ${п}`), '');
  return с.join('\n');
}

export function собрать(один) {
  const работа = изМоделей();
  const столы = [...работа.keys()].filter((к) => /^DESK-\d{3}$/.test(к) && (!один || к === один)).sort();
  // Совмещения: один человек назван за несколькими столами.
  const поЧеловеку = new Map();
  for (const к of столы) for (const ч of люди(столКарты.get(к)?.who)) { if (!поЧеловеку.has(ч)) поЧеловеку.set(ч, []); поЧеловеку.get(ч).push(к); }
  mkdirSync(ВЫХОД, { recursive: true });
  const карточки = [];
  for (const к of столы) {
    const совм = люди(столКарты.get(к)?.who).filter((ч) => (поЧеловеку.get(ч) || []).length > 1).map((ч) => `${ч}: ${поЧеловеку.get(ч).join(', ')}`);
    const карт = карточка(к, работа.get(к), совм);
    writeFileSync(path.join(ВЫХОД, `${к}.json`), JSON.stringify(карт, null, 2) + '\n');
    writeFileSync(path.join(ВЫХОД, `${к}.md`), вМД(карт));
    карточки.push(карт);
  }
  return карточки;
}

if (напрямую(import.meta.url)) {
  const арг = process.argv.slice(2);
  const один = арг.find((x) => /^DESK-\d{3}$/.test(x));
  const карточки = собрать(один);
  if (арг.includes('--probely')) {
    const счёт = {};
    for (const к of карточки) for (const п of к.пробелы) { const вид = п.split(':')[0]; счёт[вид] = (счёт[вид] || 0) + 1; }
    console.log(`Столов: ${карточки.length}`);
    for (const [в, n] of Object.entries(счёт).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(3)} · ${в}`);
  } else {
    const свод = ['# Карточки ролей · сводка', '', `Столов: ${карточки.length} · карта ${мм.version?.red} · собрано ${new Date().toISOString().slice(0, 10)}`, '', '| Стол | Процессов | Шагов | Виз | Сигналов | Решений | Лимиты числом | Кто за столом | Пробелов |', '|---|---:|---:|---:|---:|---:|---|---|---:|'];
    for (const к of карточки.sort((a, b) => b.работа.шаги.length - a.работа.шаги.length)) свод.push(`| [${к.desk}](${к.desk}.md) · ${к.название} | ${к.роли_в_процессах.length} | ${к.работа.шаги.length} | ${к.работа.визы.length} | ${к.работа.сигналы.length} | ${к.права.каталог_решений.length} | ${к.права.лимиты_числом.join(' · ') || '—'} | ${к.кто.за_столом ? 'есть' : '—'} | ${к.пробелы.length} |`);
    writeFileSync(path.join(ВЫХОД, '_svod.md'), свод.join('\n') + '\n');
    console.log(`Карточек: ${карточки.length} → roli/ (json и md), сводка roli/_svod.md`);
  }
}
