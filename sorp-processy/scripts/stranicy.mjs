// Страницы презентаций из папки «Презентации»: где упомянут процесс.
//
// Текст каждой презентации разложен по страницам (tools/tekst-pdf.mjs). Процесс
// считается упомянутым на странице, если там есть его название (не короче шести букв —
// «Касса» и «Карты» слишком общие) или код вида RLF-26. Отдельная презентация —
// файл «Описание процесса …», чья тема совпадает с названием процесса или
// который упоминает процесс чаще обзоров.

import { readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { путь, читать, ПРЕЗЕНТАЦИИ } from './mesto.mjs';

const ПАПКА = ПРЕЗЕНТАЦИИ;
const норм = (s) => String(s).toLowerCase().replace(/ё/g, 'е').replace(/[«»"“”]/g, '').replace(/\s+/g, ' ');
const экран = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const слово = (s) => new RegExp(`(?<![\\p{L}\\d-])${экран(s)}(?![\\p{L}\\d])`, 'u');

export function загрузитьСтраницы() {
  const файлы = [];
  (function обойти(d) {
    for (const f of readdirSync(путь(d))) {
      const p = path.join(d, f);
      if (statSync(путь(p)).isDirectory()) обойти(p);
      else if (p.endsWith('.txt') && !/Пояснение/.test(f)) файлы.push(p);
    }
  })(ПАПКА);
  const документы = new Map();
  const страницы = [];
  for (const файл of файлы) {
    const имя = path.basename(файл, '.txt');
    const ключ = имя.replace(/^\d{4}-\d{2}-\d{2}_Артефакт_/, '').replace(/_ред\d+$/, '');
    const [вид, тема] = ключ.split('_');
    const папка = файл.split(path.sep).includes('Сырое') ? 'Сырое' : 'Готовое';
    const части = читать(файл).split(/^=== стр\. (\d+) ===$/mu);
    const док = { ключ, файл: path.basename(файл).replace(/\.txt$/, '.pdf'), имяДок: `${вид} «${тема}»`, папка, тема: норм(тема || ''), отдельная: /^Описание процесса/.test(ключ), всегоСтраниц: (части.length - 1) / 2, путь: файл };
    документы.set(ключ, док);
    for (let i = 1; i < части.length; i += 2) страницы.push({ док, n: части[i], текст: части[i + 1], норм: норм(части[i + 1]) });
  }

  return {
    документы,
    документ: (ключ) => документы.get(ключ),
    текстСтраницы: (ключ, n) => страницы.find((с) => с.док.ключ === ключ && с.n === String(n))?.текст ?? null,
    ключФайла: (файл) => [...документы.values()].find((д) => путь(д.путь) === путь(файл))?.ключ ?? null,
    дляПроцесса(п) {
      const части = норм(п.n).split(/\s+[-—]\s+/).filter((ч) => ч.length >= 6);
      const код = п.num.length >= 4 ? норм(п.num) : null;
      const признаки = [...части.map((ч) => [слово(ч), `название «${ч}»`]), ...(код ? [[слово(код), `код ${п.num}`]] : [])];
      const найдено = [];
      for (const с of страницы) {
        const почему = признаки.filter(([re]) => re.test(с.норм)).map(([, т]) => т);
        if (почему.length) найдено.push({ ...с, почему: 'упоминает ' + почему.join(' и ') });
      }
      // Тема отдельной презентации совпадает с названием — берём её первые страницы, даже без упоминаний.
      for (const д of документы.values()) {
        if (!д.отдельная || !части.some((ч) => д.тема.includes(ч) || ч.includes(д.тема))) continue;
        if (найдено.some((с) => с.док === д)) continue;
        for (const с of страницы.filter((x) => x.док === д).slice(0, 3)) найдено.push({ ...с, почему: `тема презентации «${д.тема}» совпадает с названием процесса` });
      }
      const счёт = new Map();
      for (const с of найдено) счёт.set(с.док.ключ, (счёт.get(с.док.ключ) || 0) + 1);
      const отдельные = найдено.filter((с) => с.док.отдельная).sort((a, b) => счёт.get(b.док.ключ) - счёт.get(a.док.ключ) || a.n - b.n).slice(0, 12);
      const обзоры = найдено.filter((с) => !с.док.отдельная).slice(0, 6);
      return [...отдельные, ...обзоры].map((с) => ({ ключ: с.док.ключ, имяДок: с.док.имяДок, папка: с.док.папка, файл: с.док.файл, всегоСтраниц: с.док.всегоСтраниц, n: с.n, текст: с.текст, почему: с.почему }));
    },
  };
}
